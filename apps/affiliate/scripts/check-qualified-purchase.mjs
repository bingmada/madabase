import assert from "node:assert/strict";
import { loadAffiliateTypescript as load } from "./lib/load-affiliate-typescript.mjs";
const { compatibilityPurchaseOptions } = load("../../lib/compatibility-purchase-options.ts");
const { qualifiedPurchaseOption } = load("../../lib/compatibility-purchase.ts");
const { checkDock, checkArm } = load("../../lib/compatibility-engine.ts");
const { compareDocks } = load("../../lib/setup-decisions.ts");
const { isPublishedCommerceClick, publishedCommerceInventory } = load("../../lib/commerce-inventory.ts");
const { explicitCommerceAlternatives } = load("../../lib/commerce-paths.ts");
const { siteProducts } = load("../../lib/content.ts");
const options = compatibilityPurchaseOptions("homeoffice", "docks");
const d = {mac:"m4-air",dock:"ts4",screens:2,lid:"open",mode:"4k60",input:"hdmi",software:"yes",workload:"office",powerWatts:65,clamshellReady:"yes"};
let decisions = 0;
for (const dock of ["ts4","ud5","displaylink"]) {
  const result = checkDock({...d,dock});
  const option = qualifiedPurchaseOption(result, options);
  assert.ok(option, `${dock} has its own offer`);
  assert.equal(option.product.slug, result.productSlug);
  assert.ok(isPublishedCommerceClick(option.site, option.product.slug, option.offer.merchant));
  for (const status of ["unknown","incompatible"]) assert.equal(qualifiedPurchaseOption({...result,status},options),undefined);
  assert.equal(qualifiedPurchaseOption({...result,noBuy:"Current setup already works"},options),undefined);
  assert.equal(qualifiedPurchaseOption({...result,productSlug:"invented-model"},options),undefined);
  decisions += 5;
}
for(const candidate of compareDocks(d,"yes").candidates) assert.equal(qualifiedPurchaseOption({...candidate.result,noBuy:"Keep working setup"},options),undefined);
assert.equal(qualifiedPurchaseOption(checkDock({...d,mac:"m1-air",software:"no"}),options),undefined);
assert.equal(qualifiedPurchaseOption(checkDock({...d,mode:"other"}),options),undefined);
assert.deepEqual(compatibilityPurchaseOptions("network","docks"),[]);
assert.deepEqual(compatibilityPurchaseOptions("homeoffice","ethernet"),[]);
const arms=compatibilityPurchaseOptions("homeoffice","monitor-arms");
const a={arm:"hx",kg:10,mm:25,vesa:"100x100",construction:"approved",curved:"flat",clearance:"yes",ports:"yes",travel:"yes"};
assert.equal(qualifiedPurchaseOption(checkArm(a),arms)?.product.asin,"B01N5FTCJE");
for(const input of [{kg:9.05},{vesa:"200x200"},{alreadyOwned:"yes"},{curved:"curved"},{ports:"unknown"}]) assert.equal(qualifiedPurchaseOption(checkArm({...a,...input}),arms),undefined);
const alternative=explicitCommerceAlternatives()[0];
assert.equal(alternative.publicationStatus,"draft");
assert.equal(siteProducts("homeoffice").some(p=>p.slug===alternative.slug),false);
assert.equal(publishedCommerceInventory().filter(p=>p.slug===alternative.slug).length,1);
assert.ok(isPublishedCommerceClick("homeoffice",alternative.slug,"Amazon US"));
for(const [site,slug,merchant] of [["network",alternative.slug,"Amazon US"],["homeoffice",alternative.slug,"Amazon UK"],["homeoffice",alternative.slug+"-wrong","Amazon US"],["homeoffice","family-random-B0FH4RDV1Q","Amazon US"]]) assert.equal(isPublishedCommerceClick(site,slug,merchant),false);
console.log(JSON.stringify({passed:true,qualifiedIdentityDecisions:decisions,guardCases:15,renderedAlternativeTracked:true,draftDiscoveryStillExcluded:true,conservativeHxIdentity:true},null,2));
